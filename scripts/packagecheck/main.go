// Command packagecheck verifies the local release archives without publishing.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"context"
	"crypto/sha256"
	"debug/buildinfo"
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
	"time"
)

func main() {
	version := flag.String("version", "0.3.0-dev", "archive version without v prefix")
	flag.Parse()
	if err := checkRelease(*version); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("Verified four target archives, corresponding source, checksums and native version.")
}

func checkRelease(version string) error {
	if !regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+(-[A-Za-z0-9.-]+)?$`).MatchString(version) {
		return fmt.Errorf("invalid release version")
	}
	manifest, err := os.ReadFile("scripts/release-files.txt")
	if err != nil {
		return err
	}
	files := make(map[string][]byte)
	for _, path := range strings.Fields(string(manifest)) {
		if !fs.ValidPath(path) || strings.Contains(path, "\\") {
			return fmt.Errorf("invalid source path %q", path)
		}
		if _, exists := files[path]; exists {
			return fmt.Errorf("duplicate source path %q", path)
		}
		files[path], err = os.ReadFile(path)
		if err != nil {
			return err
		}
	}
	prefix := "my-code-dashboard-" + version
	targets := []string{"darwin-arm64", "darwin-amd64", "linux-arm64", "linux-amd64", "source"}
	dir := filepath.Join("dist", version)
	checksums, err := os.ReadFile(filepath.Join(dir, "SHA256SUMS"))
	if err != nil {
		return err
	}
	sums := make(map[string]string)
	for _, line := range strings.Split(strings.TrimSpace(string(checksums)), "\n") {
		fields := strings.Fields(line)
		if len(fields) != 2 || !regexp.MustCompile(`^[a-f0-9]{64}$`).MatchString(fields[0]) {
			return fmt.Errorf("malformed checksum line")
		}
		name := strings.TrimPrefix(fields[1], "./")
		if _, exists := sums[name]; exists {
			return fmt.Errorf("duplicate checksum %q", name)
		}
		sums[name] = fields[0]
	}
	archives, err := filepath.Glob(filepath.Join(dir, "*.tar.gz"))
	if err != nil {
		return err
	}
	if len(archives) != len(targets) || len(sums) != len(targets) {
		return fmt.Errorf("expected exactly five archives and checksums")
	}
	for _, target := range targets {
		name := prefix + "-" + target
		path := filepath.Join(dir, name+".tar.gz")
		data, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}
		if fmt.Sprintf("%x", sha256.Sum256(data)) != sums[name+".tar.gz"] {
			return fmt.Errorf("checksum mismatch for %s", name)
		}
		if err = checkArchive(data, name, target, version, files); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
	}
	return nil
}

func checkArchive(data []byte, name, target, version string, source map[string][]byte) error {
	gz, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return err
	}
	defer gz.Close()
	tr := tar.NewReader(gz)
	seen := make(map[string]bool)
	var binary, notices []byte
	for {
		h, readErr := tr.Next()
		if errors.Is(readErr, io.EOF) {
			break
		}
		if readErr != nil {
			return readErr
		}
		path := strings.TrimPrefix(h.Name, name+"/")
		if path == h.Name || (path != "" && !fs.ValidPath(strings.TrimSuffix(path, "/"))) || strings.Contains(path, "\\") {
			return fmt.Errorf("unsafe archive path %q", h.Name)
		}
		for _, part := range strings.Split(path, "/") {
			if strings.HasPrefix(part, "._") {
				return fmt.Errorf("AppleDouble metadata in archive")
			}
		}
		for key := range h.PAXRecords {
			if strings.Contains(strings.ToLower(key), "xattr") {
				return fmt.Errorf("extended attributes in archive")
			}
		}
		if h.Typeflag == tar.TypeDir {
			continue
		}
		if h.Typeflag != tar.TypeReg || seen[path] || h.Size > 128<<20 {
			return fmt.Errorf("duplicate, linked or oversized archive entry %q", path)
		}
		seen[path] = true
		content, readErr := io.ReadAll(tr)
		if readErr != nil {
			return readErr
		}
		switch {
		case target == "source" && strings.HasPrefix(path, "vendor/"):
			// Dependency source is generated by go mod vendor, not the public manifest.
		case target == "source":
			if expected, ok := source[path]; !ok || !bytes.Equal(content, expected) {
				return fmt.Errorf("unlisted or changed source file %q", path)
			}
		case path == "my-code-dashboard":
			binary = content
		case path == "THIRD_PARTY_LICENSES.txt":
			notices = content
		case path == "README.md" || path == "LICENSE" || path == "THIRD_PARTY_NOTICES.md" || strings.HasPrefix(path, "docs/"):
			if expected, ok := source[path]; !ok || !bytes.Equal(content, expected) {
				return fmt.Errorf("unlisted or changed documentation %q", path)
			}
		default:
			return fmt.Errorf("unexpected binary archive entry %q", path)
		}
	}
	if target == "source" {
		for path := range source {
			if !seen[path] {
				return fmt.Errorf("missing source file %q", path)
			}
		}
		for _, path := range []string{"vendor/modules.txt", "vendor/modernc.org/sqlite/LICENSE", "vendor/github.com/zalando/go-keyring/LICENSE"} {
			if !seen[path] {
				return fmt.Errorf("missing dependency source/notice %q", path)
			}
		}
		return nil
	}
	for path := range source {
		if (strings.HasPrefix(path, "docs/") || path == "README.md" || path == "LICENSE" || path == "THIRD_PARTY_NOTICES.md") && !seen[path] {
			return fmt.Errorf("missing documentation %q", path)
		}
	}
	return checkBinary(binary, notices, target, version)
}

func checkBinary(binary, notices []byte, target, version string) error {
	info, err := buildinfo.Read(bytes.NewReader(binary))
	if err != nil {
		return fmt.Errorf("read binary metadata: %w", err)
	}
	settings := make(map[string]string)
	for _, setting := range info.Settings {
		settings[setting.Key] = setting.Value
	}
	if info.GoVersion != "go1.26.10" || info.Path != "github.com/olegiv/my-code-dashboard/cmd/my-code-dashboard" || settings["CGO_ENABLED"] != "0" || settings["GOOS"]+"-"+settings["GOARCH"] != target {
		return fmt.Errorf("unexpected compiler, module, CGO or target metadata")
	}
	text := string(notices)
	if !strings.Contains(text, "Target: "+strings.ReplaceAll(target, "-", "/")+"; go1.26.10") {
		return fmt.Errorf("missing target-specific notices")
	}
	components := []string{"Go go1.26.10 / LICENSE", "Embedded browser assets / HTMX-LICENSE", "Embedded browser assets / ALPINE-LICENSE", "Embedded browser assets / VUE-LICENSE"}
	for _, dep := range info.Deps {
		components = append(components, dep.Path+"@"+dep.Version+" / ")
	}
	for _, component := range components {
		if !strings.Contains(text, "===== "+component) {
			return fmt.Errorf("missing component notice %q", component)
		}
	}
	if target != runtime.GOOS+"-"+runtime.GOARCH {
		return nil // Cross-target binaries are inspected, not executed.
	}
	dir, err := os.MkdirTemp("", "dashboard-package-check-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	path := filepath.Join(dir, "my-code-dashboard")
	if err = os.WriteFile(path, binary, 0700); err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, path, "--version")
	cmd.Env = []string{} // This smoke check needs no host credentials or runtime data.
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("native version smoke check failed: %w", err)
	}
	if strings.TrimSpace(string(out)) != version {
		return fmt.Errorf("native version does not match archive version")
	}
	return nil
}
